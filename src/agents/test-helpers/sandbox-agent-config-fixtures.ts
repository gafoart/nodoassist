/**
 * Sandbox agent config fixtures.
 *
 * Builds restricted agent configs for sandbox tool-policy and workspace tests.
 */
import type { NodoAssistConfig } from "../../config/types.nodoassist.js";

type AgentToolsConfig = NonNullable<
  NonNullable<NodoAssistConfig["agents"]>["list"]
>[number]["tools"];
type SandboxToolsConfig = {
  allow?: string[];
  deny?: string[];
};

export function createRestrictedAgentSandboxConfig(params: {
  agentTools?: AgentToolsConfig;
  globalSandboxTools?: SandboxToolsConfig;
  workspace?: string;
}): NodoAssistConfig {
  return {
    agents: {
      defaults: {
        sandbox: {
          mode: "all",
          scope: "agent",
        },
      },
      list: [
        {
          id: "restricted",
          workspace: params.workspace ?? "~/nodoassist-restricted",
          sandbox: {
            mode: "all",
            scope: "agent",
          },
          ...(params.agentTools ? { tools: params.agentTools } : {}),
        },
      ],
    },
    ...(params.globalSandboxTools
      ? {
          tools: {
            sandbox: {
              tools: params.globalSandboxTools,
            },
          },
        }
      : {}),
  } as NodoAssistConfig;
}
